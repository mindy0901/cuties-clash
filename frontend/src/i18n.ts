export const useLanguageStore = create<LanguageState>()(
	persist(
		(set) => ({
			language: 'en',
			setLanguage: (language) => set({ language }),
		}),
		{
			name: 'martial-cutie-language',
			partialize: (state) => ({ language: state.language }),
		},
	),
)

export function translate(text: string, values?: Record<string, string | number>): string {
	const language = useLanguageStore.getState().language
	let translated = language === 'en' ? (ENGLISH[text] ?? text) : text
	if (values) {
		for (const [key, value] of Object.entries(values)) {
			translated = translated.replaceAll(`{${key}}`, String(value))
		}
	}
	return translated
}

/**
 * The **English** form of a UI string, whatever the player's language is.
 *
 * Only the content admin page uses it: that page is a developer tool, so it always reads in English
 * while the game itself follows the EN/VI toggle. Reusing the dictionary keeps one translation table
 * instead of a second copy of every kit and stat name.
 */
export function toEnglish(text: string): string {
	return ENGLISH[text] ?? text
}
