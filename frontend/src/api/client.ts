/** Calls the backend API. Dev: the Vite proxy sends `/api` → FastAPI. Production: same origin. */

export interface ApiUser {
	id: number
	display_name: string
	email: string | null
	avatar_url: string | null
	providers: string[]
	/** Email listed in `ADMIN_EMAILS` → the content admin page is available. */
	is_admin: boolean
}

export interface ApiSession {
	authenticated: boolean
	user: ApiUser | null
	available_providers: string[]
	/** Backend asks the client to redirect to the provider when signed out. */
	auto_login: boolean
}

export interface ApiSave {
	run: Record<string, unknown> | null
	revision: number
	updated_at: string | null
}

/** Content overlay: `{ items, cuties, kits, art }` — `kits` is the catalogue, not a kit list. */
export interface ApiContent {
	items: Record<string, Record<string, unknown>>
	cuties: Record<string, Record<string, unknown>>
	/** The kit catalogue: the headings, plus every kit that differs from the code definition. */
	kits: {
		categories: { id: string; label: string; position: number }[]
		entries: Record<string, Record<string, unknown>>
	}
	/** Uploaded pictures, ready to use as `<img src>`. */
	art: Record<string, string>
}

/** One row of the kit catalogue (`kit_categories` + `kit_entries`), admin page only. */
export interface ApiKitEntry {
	id: string
	mechanic: string
	label: string | null
	categoryId: string | null
	appliesTo: string | null
	params: Record<string, number[]> | null
	position: number | null
	removed: boolean
	updatedAt: string
	updatedBy: string | null
}

export interface ApiKitCategory {
	id: string
	label: string
	position: number
	updatedAt: string
	updatedBy: string | null
}

export interface ApiContentOverride {
	kind: 'item' | 'cutie'
	entityId: string
	payload: Record<string, unknown>
	updatedAt: string
	updatedBy: string | null
}

/** One uploaded picture (metadata only — the bytes come from `/api/content/art/…`). */
export interface ApiContentArt {
	kind: 'item' | 'cutie'
	entityId: string
	version: number
	width: number
	height: number
	updatedAt: string
	updatedBy: string | null
}

export class ApiError extends Error {
	readonly status: number
	readonly code: string

	constructor(status: number, code: string, message: string) {
		super(message)
		this.name = 'ApiError'
		this.status = status
		this.code = code
	}
}

const JSON_HEADERS = { 'Content-Type': 'application/json' } as const

async function parseError(response: Response): Promise<ApiError> {
	let code = 'http_error'
	let message = `Máy chủ trả về lỗi ${response.status}.`
	try {
		const body = (await response.json()) as { error?: string; message?: string; detail?: string }
		if (typeof body.error === 'string') code = body.error
		if (typeof body.message === 'string') message = body.message
		else if (typeof body.detail === 'string') message = body.detail
	} catch {
		// Not JSON — keep the default message.
	}
	return new ApiError(response.status, code, message)
}

async function request<T>(path: string, init?: RequestInit): Promise<T> {
	const response = await fetch(path, {
		// The session cookie is httpOnly, so it has to be sent with every call.
		credentials: 'include',
		...init,
		headers: { ...JSON_HEADERS, ...init?.headers },
	})
	if (!response.ok) throw await parseError(response)
	if (response.status === 204) return undefined as T
	return (await response.json()) as T
}

export const api = {
	session: () => request<ApiSession>('/api/auth/session'),

	logout: () => request<{ ok: boolean }>('/api/auth/logout', { method: 'POST' }),

	getSave: () => request<ApiSave>('/api/me/save'),

	putSave: (run: Record<string, unknown>, revision: number) =>
		request<ApiSave>('/api/me/save', {
			method: 'PUT',
			body: JSON.stringify({ run, revision }),
		}),

	/** Game content overlay — public, anonymous players included. */
	content: () => request<ApiContent>('/api/content'),

	/** Overridden rows (with author) — admin accounts only. */
	adminContent: () =>
		request<{ overrides: ApiContentOverride[]; art: ApiContentArt[] }>('/api/admin/content'),

	putContent: (kind: 'item' | 'cutie', id: string, payload: Record<string, unknown>) =>
		request<{ override: ApiContentOverride }>(
			`/api/admin/content/${kind}/${encodeURIComponent(id)}`,
			{ method: 'PUT', body: JSON.stringify(payload) },
		),

	/** Deleting an override returns the entity to its code default. */
	deleteContent: (kind: 'item' | 'cutie', id: string) =>
		request<{ ok: boolean }>(`/api/admin/content/${kind}/${encodeURIComponent(id)}`, {
			method: 'DELETE',
		}),

	/**
	 * Delete one kit from the **whole game**: the server marks it removed and detaches it from every
	 * item and Cutie. `…/remove` is its own path so a field edit can never reach it by accident.
	 */
	removeKit: (id: string) =>
		request<{ ok: boolean }>(`/api/admin/content/kit/${encodeURIComponent(id)}/remove`, {
			method: 'POST',
			body: JSON.stringify({ removed: true }),
		}),

	/** Create a kit on top of an engine mechanic (the id is generated by the server). */
	createKit: (payload: Record<string, unknown>) =>
		request<{ entry: ApiKitEntry }>('/api/admin/content/kit', {
			method: 'POST',
			body: JSON.stringify(payload),
		}),

	/** Save one kit: label, catalogue (**the move**), who may carry it, default numbers, removed. */
	saveKit: (id: string, payload: Record<string, unknown>) =>
		request<{ entry: ApiKitEntry }>(`/api/admin/content/kit/${encodeURIComponent(id)}`, {
			method: 'PUT',
			body: JSON.stringify(payload),
		}),

	/** Drop the catalogue row (a code kit goes back to its definition; a created kit is gone). */
	deleteKit: (id: string) =>
		request<{ ok: boolean }>(`/api/admin/content/kit/${encodeURIComponent(id)}`, { method: 'DELETE' }),

	createKitCategory: (payload: { label: string }) =>
		request<{ category: ApiKitCategory }>('/api/admin/content/kit-category', {
			method: 'POST',
			body: JSON.stringify(payload),
		}),

	saveKitCategory: (id: string, payload: Record<string, unknown>) =>
		request<{ category: ApiKitCategory }>(
			`/api/admin/content/kit-category/${encodeURIComponent(id)}`,
			{ method: 'PUT', body: JSON.stringify(payload) },
		),

	deleteKitCategory: (id: string) =>
		request<{ ok: boolean }>(`/api/admin/content/kit-category/${encodeURIComponent(id)}`, {
			method: 'DELETE',
		}),

	/**
	 * Upload the picture of one entity as a **raw PNG body**, already cropped in the browser to the
	 * item's footprint. ❌ Not multipart: a Blob can be sent directly, and base64 in JSON would add a
	 * third to the size for nothing.
	 */
	uploadArt: (kind: 'item' | 'cutie', id: string, png: Blob) =>
		request<{ art: ApiContentArt }>(`/api/admin/content/${kind}/${encodeURIComponent(id)}/art`, {
			method: 'PUT',
			headers: { 'Content-Type': 'image/png' },
			body: png,
		}),

	/** Remove the uploaded picture (the entity returns to its bundled art, then the emoji). */
	deleteArt: (kind: 'item' | 'cutie', id: string) =>
		request<{ ok: boolean }>(`/api/admin/content/${kind}/${encodeURIComponent(id)}/art`, {
			method: 'DELETE',
		}),

	/** Login start URL — the browser navigates itself to the provider. */
	loginUrl: (provider: string) => `/api/auth/${encodeURIComponent(provider)}/login`,
}
